const MS_HORA = 60 * 60 * 1000;
const MS_DIA = 24 * MS_HORA;

function isoDeltaHoras(horas: number): string {
  return new Date(Date.now() + horas * MS_HORA).toISOString();
}

function isoDeltaDias(dias: number): string {
  return new Date(Date.now() + dias * MS_DIA).toISOString();
}

function dataIsoDeltaDias(dias: number): string {
  return new Date(Date.now() + dias * MS_DIA).toISOString().slice(0, 10);
}

